# Long vLLM/OAT jobs occasionally lose an actor while the learner remains
# blocked on its RPC. Restart jobs can opt into checkpoint discovery without
# hard-coding a particular debug timestamp: choose the numerically highest
# DeepSpeed checkpoint across every coherent attempt in this run directory.
if [[ "${OAT_ZERO_AUTO_RESUME:-0}" == "1" && -z "${OAT_ZERO_RESUME_DIR:-}" ]]; then
  best_checkpoint=""
  best_step=-1
  while IFS= read -r candidate; do
    tag="${candidate##*/}"
    raw_step="${tag#step_}"
    [[ "$raw_step" =~ ^[0-9]+$ ]] || continue
    step=$((10#$raw_step))
    if (( step > best_step )) || {
      (( step == best_step )) && [[ -n "$best_checkpoint" && "$candidate" -nt "$best_checkpoint" ]]
    }; then
      best_checkpoint="$candidate"
      best_step="$step"
    fi
  done < <(
    find "$SAVE_PATH" -maxdepth 4 -type d -path '*/checkpoints/step_*' -print \
      2>/dev/null || true
  )
  if [[ -n "$best_checkpoint" ]]; then
    export OAT_ZERO_RESUME_DIR="${best_checkpoint%/*}"
    export OAT_ZERO_RESUME_TAG="${best_checkpoint##*/}"
    echo "[experiment] auto_resume=${OAT_ZERO_RESUME_DIR}/${OAT_ZERO_RESUME_TAG}"
  else
    echo "[experiment] auto_resume=no checkpoint found; starting from initialization"
  fi
fi

